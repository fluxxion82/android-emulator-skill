#!/usr/bin/env python3
"""
Progressive disclosure cache for large outputs.

Implements cache system to support progressive disclosure pattern:
- Return concise summary with cache_id for large outputs
- User retrieves full details on demand via cache_id
- Reduces token usage by 96% for common queries

Cache directory: ~/.android-emulator-skill/cache/
Cache expiration: Configurable per cache type (default 1 hour)

Entries are written atomically (temp file + ``os.replace``), ids carry a random
8-hex-digit suffix so two saves in one second cannot practically collide (it
makes a clash improbable, not impossible), and an entry that cannot be
read is reported as corrupt (:class:`CacheCorruptionError`) and kept -- never
deleted as though it had expired.

Used by:
- gradle/cache.py (``build_and_test.py`` build results, ``--get-*`` / ``--list-builds``)
- container.py (large ``cat`` output)
"""

import contextlib
import json
import os
import re
import tempfile
import uuid
from datetime import datetime, timedelta
from pathlib import Path

# Cache ids are generated by save() as "<prefix>-<YYYYmmdd>-<HHMMSS>-<hex8>".
# Nothing parses one by position: callers pass the whole id back. Anything
# outside this alphabet cannot be one, and separators or ".." would let an id
# address files outside the cache directory.
_SAFE_CACHE_ID_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*")

# Hex digits of a uuid4 appended to every id. The timestamp alone has
# one-second granularity, so two saves of one type in the same second used to
# get the same id and the second silently replaced the first.
_ID_SUFFIX_HEX = 8


class CacheCorruptionError(RuntimeError):
    """A cache entry exists but cannot be read as one: corrupt, not expired.

    Raised by :meth:`ProgressiveCache.get` for an entry whose file does not
    decode as JSON, is not an object, or has no valid ``created_at``. The file
    is left where it is -- deleting it would hide the corruption as an expiry,
    which is what this cache used to do. A ``RuntimeError`` so the CLI boundary
    (:mod:`common.cli`) reports it as one refusal with :attr:`remedy`.

    Attributes:
        path: The entry's file.
        remedy: What the caller should do about it.
    """

    def __init__(self, path: Path, reason: str):
        super().__init__(f"cache entry {path} is corrupt, not expired: {reason}")
        self.path = path
        self.remedy = (
            f"The file was kept for inspection. Delete {path} and re-run the command "
            "that produced the entry to cache it again."
        )


def default_cache_dir() -> Path:
    """The skill's cache root, ``~/.android-emulator-skill/cache``.

    Resolved per call, not at import, so it follows ``HOME`` as the process
    sees it. Anything the skill writes on the caller's behalf without being
    told where -- progressive-disclosure entries, ``app_state_capture``'s
    snapshots -- goes under here, never into the caller's working directory.
    """
    return Path("~/.android-emulator-skill/cache").expanduser()


class ProgressiveCache:
    """Cache for progressive disclosure pattern.

    Stores large outputs with timestamped IDs for on-demand retrieval.
    Automatically cleans up expired entries; a corrupt entry is reported
    (:class:`CacheCorruptionError`) and kept, never swept as expired.
    """

    def __init__(self, cache_dir: str | None = None, max_age_hours: int = 1):
        """Initialize cache system.

        Args:
            cache_dir: Cache directory path (default: ~/.android-emulator-skill/cache/)
            max_age_hours: Max age for cache entries before expiration (default: 1 hour)
        """
        if cache_dir is None:
            cache_dir = str(default_cache_dir())

        self.cache_dir = Path(cache_dir)
        self.max_age_hours = max_age_hours

        # Create cache directory if needed
        self.cache_dir.mkdir(parents=True, exist_ok=True)

    def save(self, data: dict, cache_type: str) -> str:
        """Save data to cache and return cache_id.

        Args:
            data: Dictionary data to cache
            cache_type: Type of cache ('simulator-list', 'build-result', 'container-cat', etc.)

        Returns:
            Cache ID like 'simulator-20251028-143052-1a2b3c4d' for use in
            progressive disclosure: the type's first word, the time, and a
            random 8-hex-digit suffix, so two saves in one second cannot
            practically share an id.

        The entry is written to a temp file in the cache directory and moved
        into place with ``os.replace``, so a reader sees either no entry or the
        whole of it -- never a truncated file. A failed write removes its temp
        file and re-raises.

        Example:
            cache_id = cache.save({'devices': [...]}, 'simulator-list')
            # Returns: 'simulator-20251028-143052-1a2b3c4d'
        """
        now = datetime.now()
        cache_prefix = cache_type.split("-", maxsplit=1)[0]  # e.g. 'build' from 'build-result'
        suffix = uuid.uuid4().hex[:_ID_SUFFIX_HEX]
        cache_id = f"{cache_prefix}-{now.strftime('%Y%m%d-%H%M%S')}-{suffix}"
        entry = {
            "cache_id": cache_id,
            "cache_type": cache_type,
            "created_at": now.isoformat(),
            "data": data,
        }

        # The temp name ends in ".tmp", so the "*.json" globs below never see it.
        fd, tmp_name = tempfile.mkstemp(
            dir=self.cache_dir, prefix=f".{cache_id}.", suffix=".json.tmp"
        )
        tmp_path = Path(tmp_name)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                json.dump(entry, f, indent=2)
                f.flush()
                os.fsync(f.fileno())
            # Path.replace is os.replace: atomic within one directory.
            tmp_path.replace(self.cache_dir / f"{cache_id}.json")
        except BaseException:
            with contextlib.suppress(OSError):
                tmp_path.unlink(missing_ok=True)
            raise

        return cache_id

    def get(self, cache_id: str, cache_type: str | None = None) -> dict | None:
        """Retrieve data from cache by cache_id.

        Args:
            cache_id: Cache ID from save() or list_entries()
            cache_type: When given, only an entry saved under this type is
                answered; another type's entry reads as None and is kept. A
                reader that knows what it cached passes it, so another
                script's data with the same keys is never taken for its own.

        Returns:
            Cached data dictionary, or None if not found/expired (or, with
            ``cache_type``, of another type). An expired entry is deleted,
            unless it is another type's: this cache's max age is not that
            type's, so it is kept whatever its age.

        Raises:
            CacheCorruptionError: The entry exists but cannot be read as one.
                The file is kept: corrupt is not expired.

        Example:
            data = cache.get('simulator-20251028-143052-1a2b3c4d')
            if data:
                print(f"Found {len(data)} devices")
        """
        cache_file = self._entry_path(cache_id)
        if cache_file is None:
            return None

        try:
            entry, created_at = self._read_entry(cache_file)
        except FileNotFoundError:
            return None

        # Type before age. Readers share this directory and keep their entries
        # for different lengths of time, so this reader's max age says nothing
        # about another type's entry: it is refused and left for its own reader.
        if cache_type is not None and entry.get("cache_type") != cache_type:
            return None
        if self._is_expired(created_at):
            cache_file.unlink(missing_ok=True)
            return None
        return entry.get("data")

    def list_entries(self, cache_type: str | None = None) -> list:
        """List available cache entries with metadata.

        Args:
            cache_type: Filter by type (e.g., 'simulator-list'), or None for all

        Returns:
            List of cache entries with id, type, created_at, age_seconds.
            Expired entries are deleted on the way (with ``cache_type``, only
            that type's: another type's entry is kept). A corrupt entry is skipped
            and kept -- its type cannot be read, so it belongs to no listing;
            :meth:`corrupt_entries` names them.

        Example:
            entries = cache.list_entries('simulator-list')
            for entry in entries:
                print(f"{entry['id']} - {entry['age_seconds']}s old")
        """
        entries = []

        for cache_file in sorted(self.cache_dir.glob("*.json"), reverse=True):
            try:
                entry, created_at = self._read_entry(cache_file)
            except (OSError, CacheCorruptionError):
                continue

            # Filter by type if specified -- before the age check, as in get():
            # a typed listing never expires another type's entry.
            if cache_type and entry.get("cache_type") != cache_type:
                continue

            if self._is_expired(created_at):
                cache_file.unlink(missing_ok=True)
                continue

            age_seconds = (datetime.now() - created_at).total_seconds()
            entries.append(
                {
                    "id": entry.get("cache_id"),
                    "type": entry.get("cache_type"),
                    "created_at": entry.get("created_at"),
                    "age_seconds": int(age_seconds),
                }
            )

        return entries

    def cleanup(self, max_age_hours: int | None = None, cache_type: str | None = None) -> int:
        """Remove expired cache entries.

        Args:
            max_age_hours: Age threshold (default: uses instance max_age_hours)
            cache_type: When given, only entries of this type are considered;
                a reader sweeping its own type passes it, because its max age
                is not another type's.

        Returns:
            Number of expired entries deleted. A corrupt entry is neither
            deleted nor counted: it is skipped and kept, and
            :meth:`corrupt_entries` names it. A file that cannot be opened is
            skipped too.

        Example:
            deleted = cache.cleanup()
            print(f"Deleted {deleted} expired cache entries")
        """
        deleted = 0

        for cache_file in self.cache_dir.glob("*.json"):
            try:
                entry, created_at = self._read_entry(cache_file)
            except (OSError, CacheCorruptionError):
                continue
            if cache_type is not None and entry.get("cache_type") != cache_type:
                continue
            if self._is_expired(created_at, max_age_hours):
                cache_file.unlink(missing_ok=True)
                deleted += 1

        return deleted

    def corrupt_entries(self) -> list[Path]:
        """The entry files that exist but cannot be read as entries.

        :meth:`get` raises :class:`CacheCorruptionError` for one of these, and
        :meth:`list_entries` and :meth:`cleanup` skip them without deleting
        them. Temp files from an interrupted :meth:`save` (``*.json.tmp``)
        are not entries and are not listed.

        Returns:
            Paths of corrupt entries, sorted.
        """
        corrupt = []
        for cache_file in sorted(self.cache_dir.glob("*.json")):
            try:
                self._read_entry(cache_file)
            except CacheCorruptionError:
                corrupt.append(cache_file)
            except OSError:
                continue
        return corrupt

    def clear(self, cache_type: str | None = None) -> int:
        """Clear all cache entries of a type.

        Args:
            cache_type: Type to clear (e.g., 'simulator-list'), or None to clear all

        Returns:
            Number of entries deleted. A typed clear skips and keeps a corrupt
            entry, as every other operation does -- even one whose
            ``cache_type`` happens to be readable. ``clear()`` with no type
            removes every entry file, corrupt ones included.

        Example:
            cleared = cache.clear('simulator-list')
            print(f"Cleared {cleared} simulator list entries")
        """
        deleted = 0

        for cache_file in self.cache_dir.glob("*.json"):
            if cache_type is None:
                # Clear all
                cache_file.unlink()
                deleted += 1
            else:
                try:
                    entry, _created_at = self._read_entry(cache_file)
                except (OSError, CacheCorruptionError):
                    continue
                if entry.get("cache_type") == cache_type:
                    cache_file.unlink(missing_ok=True)
                    deleted += 1

        return deleted

    def _entry_path(self, cache_id: str) -> Path | None:
        """Resolve a cache id to a file inside the cache directory.

        Cache ids come from callers -- ``build_and_test.py --get-log <ID>``
        passes one straight through -- and the lookup path both reads the file
        and, when it is an expired entry, deletes it. An id that can address
        anything outside the cache directory therefore means an arbitrary read
        and an arbitrary ``*.json`` delete.

        Two independent checks, because either alone has gaps: the character
        allowlist rejects separators and ``..`` outright, and the containment
        check catches anything that still resolves outside the directory (a
        symlinked cache dir, say).

        Args:
            cache_id: Caller-supplied identifier.

        Returns:
            The entry path, or None if the id is not a plain cache id.
        """
        if not cache_id or not _SAFE_CACHE_ID_RE.fullmatch(cache_id):
            return None

        candidate = self.cache_dir / f"{cache_id}.json"
        try:
            resolved_dir = self.cache_dir.resolve()
            resolved_entry = candidate.resolve()
        except OSError:
            return None

        if resolved_entry.parent != resolved_dir:
            return None
        return candidate

    @staticmethod
    def _read_entry(cache_file: Path) -> tuple[dict, datetime]:
        """Read an entry file and its creation time.

        Args:
            cache_file: Path to the entry's ``.json`` file.

        Returns:
            ``(entry, created_at)``.

        Raises:
            OSError: The file could not be opened (``FileNotFoundError`` when
                there is no such entry).
            CacheCorruptionError: The file does not decode as JSON, is not an
                object, or has no valid ``created_at``.
        """
        with open(cache_file, encoding="utf-8") as f:
            try:
                entry = json.load(f)
            except ValueError as error:
                # ValueError, not just JSONDecodeError: bad UTF-8 raises
                # UnicodeDecodeError, and well-formed JSON holding an integer
                # longer than sys.get_int_max_str_digits() raises a plain
                # ValueError. All three are a file that cannot be read back.
                raise CacheCorruptionError(
                    cache_file, f"it does not decode as JSON ({error})"
                ) from error

        if not isinstance(entry, dict):
            raise CacheCorruptionError(
                cache_file, f"it holds a JSON {type(entry).__name__}, not an entry object"
            )
        raw_created = entry.get("created_at")
        if not isinstance(raw_created, str):
            raise CacheCorruptionError(cache_file, "it has no created_at timestamp")
        try:
            created_at = datetime.fromisoformat(raw_created)
        except ValueError as error:
            raise CacheCorruptionError(
                cache_file, f"its created_at {raw_created!r} is not a timestamp"
            ) from error
        return entry, created_at

    def _is_expired(self, created_at: datetime, max_age_hours: int | None = None) -> bool:
        """Whether an entry created at ``created_at`` is older than the threshold.

        Age only: an entry whose creation time cannot be read is corrupt, and
        :meth:`_read_entry` has said so before this is asked.

        Args:
            created_at: The entry's creation time.
            max_age_hours: Age threshold (default: uses instance max_age_hours)

        Returns:
            True if the entry is older than max_age_hours
        """
        if max_age_hours is None:
            max_age_hours = self.max_age_hours
        return datetime.now() - created_at > timedelta(hours=max_age_hours)


# Module-level cache instances (lazy-loaded)
_cache_instances = {}


def get_cache(cache_dir: str | None = None) -> ProgressiveCache:
    """Get or create global cache instance.

    Args:
        cache_dir: Custom cache directory (uses default if None)

    Returns:
        ProgressiveCache instance
    """
    # Use cache_dir as key, or 'default' if None
    key = cache_dir or "default"

    if key not in _cache_instances:
        _cache_instances[key] = ProgressiveCache(cache_dir)

    return _cache_instances[key]
